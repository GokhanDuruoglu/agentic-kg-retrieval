"""LLM relation consolidation — collapse the OpenIE relation explosion into a canonical vocab.

OpenIE produces thousands of fragmented / synonymous relation types (e.g. BIRTH_DATE vs
DATE_OF_BIRTH, RELEASE_YEAR vs PUBLICATION_DATE). This pass:

  1. asks the LLM to build a CANONICAL relation vocabulary from the most frequent phrases,
  2. maps every relation phrase -> a canonical phrase (chunked LLM calls; unmappable -> "other"),
  3. REMAPS the existing kg.jsonl edges to the canonical relation types,
  4. once relation types are canonical, applies two relation-signalled entity-resolution passes
     that only make sense post-consolidation (raw phrases are too noisy to trust for this):
       - ABBREVIATION edges: cross-link both endpoints as EACH OTHER'S alias. Does not merge the
         nodes (an abbreviation and its expansion are the same referent for lookups, but keeping
         them as distinct nodes with a real edge between them is safer than presuming identity).
       - BIRTH_NAME / FULL_NAME edges: cross-alias the same way, AND additionally propose the
         pair as a safe_merge() candidate (same veto gate build_openie's title/embedding
         candidates already go through — a "birth name" edge is strong identity evidence, but a
         bad extraction or contradicting facts still block the merge).
  5. rewrites schema.json (+ relation_map.json) from the final, post-merge edge set.

It does NOT re-extract — it only relabels/re-links what's already in kg.jsonl (the pre-pass graph
is backed up to kg_raw.jsonl, and the phrase->canonical map to relation_map.json). After running,
reload Neo4j (``akg graph load``).

    akg graph build --step consolidate [--reuse-map]
"""

import argparse
import json
import re
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

from . import settings as S  # noqa: E402
from .resolve import apply_id_remap, rel_type_token, safe_merge  # noqa: E402
from .settings import DATA_DIR  # noqa: E402

# Alias-signalling relations, matched by KEYWORD/SUBSTRING on the canonical phrase (name, lower-
# cased) rather than an exact relation-type token. The canonical vocabulary is regenerated by an
# LLM call every run that doesn't pass --reuse-map (build_vocabulary()), so the exact wording is
# NOT stable across runs — one run named this concept "alias", another named it "also_known_as".
# Exact-token matching silently misses whichever wording didn't come up that run (observed: a
# real 2wiki-judged run put 1,535 of ~1,540 alias-signal edges under "also_known_as", leaving only
# 5 under the literal "alias"/"birth_name"/"full_name" tokens). Substring matching on the
# human-readable phrase is the same robustness trick resolve.py's _EXCLUSIVE_PHRASE_BUCKETS
# already uses for exactly this reason.
#
# ABBREVIATION-signalling relations are cross-aliased only (no merge — see module docstring: an
# abbreviation and its expansion are kept as distinct nodes). Alias/birth-name/full-name-
# signalling relations are proposed as safe_merge() candidates — an entity's `aliases` list is
# otherwise populated ONLY by exact-string-match dedup (Resolver.add) and entity merges
# (safe_merge/apply_id_remap); an extracted edge between two DIFFERENT entity nodes never touches
# either side's aliases list on its own. Merging folds the alias name into the survivor's aliases
# list directly (apply_id_remap); a candidate that fails the veto is cross-aliased instead, so the
# fact isn't silently dropped.
_ALIAS_ONLY_KEYWORDS = ("abbreviation", "acronym")
_ALIAS_MERGE_KEYWORDS = (
    "also_known_as", "alias", "aka", "pseudonym", "nickname", "pen_name", "stage_name",
    "birth_name", "maiden_name", "née", "nee_", "full_name", "real_name", "legal_name",
    "formal_name",
)


def _matches_keywords(name: str, keywords: tuple[str, ...]) -> bool:
    n = (name or "").lower()
    return any(k in n for k in keywords)

# Consolidation is ~tens of calls (small); stage "consolidate" of configs/graph_build.yaml (a strong model, temperature 0).
def _cons_llm():
    return S.llm("consolidate")


def _parse_json(content: str):
    s = re.sub(r"^```[a-z]*\n?", "", content.strip(), flags=re.IGNORECASE).strip().rstrip("`").strip()
    try:
        return json.loads(s)
    except Exception:
        pass
    for op, cl in (("{", "}"), ("[", "]")):
        i = s.find(op)
        if i == -1:
            continue
        depth = 0
        for j in range(i, len(s)):
            if s[j] == op:
                depth += 1
            elif s[j] == cl:
                depth -= 1
                if depth == 0:
                    try:
                        return json.loads(s[i:j + 1])
                    except Exception:
                        break
    return None


_VOCAB_SYSTEM = """You normalize a knowledge-graph RELATION vocabulary.

Given relation phrases (with frequencies), produce a CANONICAL, deduplicated vocabulary of
snake_case relation names that MERGES synonyms and near-duplicates, e.g.:
  "birth date", "date of birth", "born on"      -> date_of_birth
  "release year", "publication date", "released"-> publication_date
  "directed by", "director of"                  -> director
Prefer concise, general relation names. Output STRICT JSON:
  {{"vocabulary": ["date_of_birth", "spouse", "director", ...]}}
Aim for at most about {target} canonical relations covering the common cases. JSON only."""

_MAP_SYSTEM = """You map knowledge-graph relation phrases to a canonical vocabulary.

Canonical vocabulary (choose ONLY from these):
{vocab}

For each input phrase, return the single best-matching canonical relation. If none fits
reasonably, return "other". Output STRICT JSON: an object mapping each input phrase to its
canonical relation, e.g. {{"birth date": "date_of_birth", "weird rel": "other"}}. JSON only."""


def build_vocabulary(rel_names_by_count: list[tuple[str, int]], vocab_size: int,
                     target: int) -> list[str]:
    """One LLM call over the top phrases -> canonical snake_case vocabulary."""
    seed = rel_names_by_count[:vocab_size]
    listing = "\n".join(f"- {name} ({cnt})" for name, cnt in seed)
    out = _cons_llm().chat(_VOCAB_SYSTEM.format(target=target),
                "Relation phrases:\n" + listing)
    parsed = _parse_json(out["content"]) or {}
    vocab = parsed.get("vocabulary") if isinstance(parsed, dict) else None
    vocab = [rel_type_token(v) for v in (vocab or []) if v]
    # Always include 'other' as a fallback bucket.
    seen, uniq = set(), []
    for v in vocab + ["OTHER"]:
        if v not in seen:
            seen.add(v); uniq.append(v)
    return uniq


def _map_chunk(phrases: list[str], vocab_str: str) -> dict[str, str]:
    out = _cons_llm().chat(_MAP_SYSTEM.format(vocab=vocab_str),
                "Phrases:\n" + "\n".join(f"- {p}" for p in phrases))
    parsed = _parse_json(out["content"])
    if not isinstance(parsed, dict):
        return {}
    return {str(k): str(v) for k, v in parsed.items()}


def _load_partial_mapping(path: Path) -> dict[str, str]:
    """Resumable cache for the phrase->canonical mapping stage: one JSON object per completed
    chunk, appended as it finishes (mirrors openie.py's/judge_openie.py's per-batch JSONL
    append). Unlike the final relation_map.json (written once, at the very end), this survives
    a kill/crash mid-mapping — the vocab+mapping stage otherwise has zero durability and a
    rerun would re-pay for every LLM call already made.
    """
    if not path.exists():
        return {}
    mapping: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            mapping.update(json.loads(line))
        except Exception:
            continue
    return mapping


def _cross_alias(entity_by_id: dict[str, dict], id_a: str, id_b: str) -> None:
    """Add each entity's name+aliases as aliases on the OTHER — no id change, no merge."""
    ea, eb = entity_by_id.get(id_a), entity_by_id.get(id_b)
    if not ea or not eb:
        return
    names_a = {ea["name"], *(ea.get("aliases") or [])}
    names_b = {eb["name"], *(eb.get("aliases") or [])}
    ea["aliases"] = sorted((set(ea.get("aliases") or []) | names_b) - {ea["name"]})
    eb["aliases"] = sorted((set(eb.get("aliases") or []) | names_a) - {eb["name"]})


def _apply_relation_signals(objs: list[dict]) -> list[dict]:
    """Post-canonicalization alias/merge pass (see module docstring). `objs` are the parsed
    kg.jsonl lines with FINAL canonical rel_type/name already applied to every edge. Returns a
    new typed-JSONL line list (passages unchanged; entities/edges/mentions folded through any
    committed merges).
    """
    passages = [o for o in objs if o.get("kind") == "passage"]
    entities = [dict(o) for o in objs if o.get("kind") == "entity"]
    edges = {(o["subject_id"], o["object_id"], o["rel_type"], o["name"], o.get("passage_id"))
             for o in objs if o.get("kind") == "edge"}
    mentions = {(o["entity_id"], o["passage_id"]) for o in objs if o.get("kind") == "mention"}

    entity_by_id = {e["id"]: e for e in entities}
    merge_candidates: list[tuple[str, str]] = []
    identity_relations: set[str] = set()  # canonical phrases actually used as merge signals below
    for (s, o, _rt, rn, _p) in edges:
        alias_only = _matches_keywords(rn, _ALIAS_ONLY_KEYWORDS)
        alias_merge = _matches_keywords(rn, _ALIAS_MERGE_KEYWORDS)
        if alias_only or alias_merge:
            _cross_alias(entity_by_id, s, o)
        if alias_merge:
            merge_candidates.append((s, o))
            identity_relations.add((rn or "").strip().lower())

    if merge_candidates:
        # relation_canon=None: edge names here are ALREADY the final canonical phrases, so no
        # further translation is needed for the veto checks' bucket matching. identity_relations
        # exempts the very alias/birth-name/full-name edge that proposed each candidate from the
        # already-connected veto (that edge asserts sameness, not distinctness — see safe_merge()
        # docstring); without it every candidate would veto itself via its own edge. Built from
        # the ACTUAL canonical phrases matched above, not a hardcoded guess, so it's correct
        # regardless of which wording this run's vocabulary happened to settle on.
        id_remap = safe_merge(entities, edges, merge_candidates,
                              identity_relations=identity_relations)
        print(f"  relation-signalled merge: {len(merge_candidates)} candidate(s) "
              f"({', '.join(sorted(identity_relations))}) -> committed {len(id_remap)} merge(s)")
        entities, edges, mentions = apply_id_remap(entities, edges, mentions, id_remap)

    # Drop any self-referential edge a merge may have produced (same unconditional guard as
    # build_openie's assembly step).
    before = len(edges)
    edges = {e for e in edges if e[0] != e[1]}
    if before != len(edges):
        print(f"  dropped {before - len(edges)} self-referential edge(s) from merges")

    return (
        [{"kind": "passage", **p} for p in passages] +
        [{"kind": "entity", **e} for e in entities] +
        [{"kind": "edge", "subject_id": s, "object_id": o, "rel_type": rt, "name": rn,
          "passage_id": p} for (s, o, rt, rn, p) in edges] +
        [{"kind": "mention", "entity_id": e, "passage_id": p} for (e, p) in mentions]
    )


def consolidate(benchmark: str, vocab_size: int, target: int, chunk: int, workers: int,
                reuse_map: bool = False) -> None:
    d = DATA_DIR / benchmark
    kg_path = d / "kg.jsonl"
    map_path = d / "relation_map.json"
    if not kg_path.exists():
        raise SystemExit(f"kg.jsonl not found: {kg_path}")

    # Collect relation phrases (the human 'name' on each edge) with counts.
    lines = kg_path.read_text(encoding="utf-8").splitlines()
    objs = [json.loads(l) for l in lines if l.strip()]
    from collections import Counter
    name_counts = Counter(o["name"] for o in objs if o.get("kind") == "edge" and o.get("name"))
    rel_by_count = name_counts.most_common()
    phrases = [name for name, _ in rel_by_count]
    print(f"  {len(rel_by_count)} distinct relation phrases over "
          f"{sum(name_counts.values())} edges")

    if reuse_map:
        # Reapply a previously-saved phrase -> canonical mapping with ZERO new LLM calls
        # (e.g. after re-running build_openie from the extraction cache, which regenerates
        # kg.jsonl with raw un-consolidated relation phrases — the phrases themselves are
        # unaffected by entity-resolution changes, so the old map still applies cleanly).
        if not map_path.exists():
            raise SystemExit(f"--reuse-map given but no saved map at {map_path}")
        saved: dict[str, str] = json.loads(map_path.read_text(encoding="utf-8"))
        print(f"  reusing saved relation_map.json ({len(saved)} phrases) — no LLM calls")
        mapping = saved
    else:
        vocab_cache_path = d / "relation_vocab_partial.json"
        map_cache_path = d / "relation_map_partial.jsonl"

        # 1) canonical vocabulary — cached too: a crash right after this single call shouldn't
        #    force re-deriving it (the mapping stage below needs the SAME vocab to resume into).
        if vocab_cache_path.exists():
            vocab = json.loads(vocab_cache_path.read_text(encoding="utf-8"))
            print(f"  reusing cached vocabulary ({len(vocab)} relations) from a prior "
                  f"interrupted run")
        else:
            vocab = build_vocabulary(rel_by_count, vocab_size, target)
            vocab_cache_path.write_text(json.dumps(vocab, ensure_ascii=False), encoding="utf-8")
        print(f"  canonical vocabulary: {len(vocab)} relations -> {', '.join(vocab[:20])}"
              f"{' ...' if len(vocab) > 20 else ''}")
        vocab_human = ", ".join(v.lower() for v in vocab)

        # 2) map every phrase -> canonical (chunked, low concurrency for rate limits). Resumable:
        #    only the phrases NOT already in a prior interrupted run's cache get re-submitted.
        mapping = _load_partial_mapping(map_cache_path)
        if mapping:
            print(f"  resuming: {len(mapping)} phrase(s) already mapped from a prior "
                  f"interrupted run")
        todo = [p for p in phrases if p not in mapping]
        chunks = [todo[i:i + chunk] for i in range(0, len(todo), chunk)]
        print(f"  mapping {len(todo)} phrase(s) in {len(chunks)} chunk(s) @ {workers} worker(s)...")
        if chunks:
            with map_cache_path.open("a", encoding="utf-8") as fh:
                with ThreadPoolExecutor(max_workers=workers) as pool:
                    futs = {pool.submit(_map_chunk, c, vocab_human): c for c in chunks}
                    done = 0
                    for fut in as_completed(futs):
                        try:
                            result = fut.result()
                        except Exception as exc:
                            print(f"    ⚠ chunk failed ({type(exc).__name__}: {exc})")
                            result = {}
                        if result:
                            mapping.update(result)
                            fh.write(json.dumps(result, ensure_ascii=False) + "\n")
                            fh.flush()
                        done += 1
                        if done % 10 == 0 or done == len(chunks):
                            print(f"    mapped {done}/{len(chunks)} chunks")

    # Resolve each phrase -> canonical token (default: keep own token if unmapped/other-but-frequent).
    def canon(name: str) -> tuple[str, str]:
        c = (mapping.get(name) or "").strip()
        if not c or c.lower() == "other":
            return "RELATED_TO", "related to"
        return rel_type_token(c), c.lower()

    phrase_map = {name: canon(name) for name in phrases}

    # 3) apply the canonical relation types to every edge; back up the raw graph first.
    (d / "kg_raw.jsonl").write_text("\n".join(lines) + "\n", encoding="utf-8")
    for o in objs:
        if o.get("kind") == "edge":
            tok, nm = phrase_map.get(o.get("name"), ("RELATED_TO", "related to"))
            o["rel_type"], o["name"] = tok, nm

    # 4) relation-signalled alias/merge pass (see module docstring) — needs canonical rel_type,
    #    hence run AFTER step 3. Folds any committed merges into entities/edges/mentions.
    objs = _apply_relation_signals(objs)

    # 5) rewrite kg.jsonl + schema.json from the final edge set.
    rel_counts = Counter()
    rel_name = {}
    with kg_path.open("w", encoding="utf-8") as fh:
        for o in objs:
            if o.get("kind") == "edge":
                rel_counts[o["rel_type"]] += 1
                rel_name[o["rel_type"]] = o["name"]
            fh.write(json.dumps(o, ensure_ascii=False) + "\n")

    relations = [{"type": t, "name": rel_name[t], "count": rel_counts[t]}
                 for t in sorted(rel_counts, key=lambda t: (-rel_counts[t], t))]
    schema = json.loads((d / "schema.json").read_text(encoding="utf-8"))
    schema["relations"] = relations
    (d / "schema.json").write_text(json.dumps(schema, indent=2, ensure_ascii=False), encoding="utf-8")
    (d / "relation_map.json").write_text(
        json.dumps({k: v[1] for k, v in phrase_map.items()}, indent=2, ensure_ascii=False),
        encoding="utf-8")

    # relation_map.json above is now the authoritative record — drop the resumability caches so
    # a later run doesn't silently resume into a stale vocab/mapping from this completed run.
    (d / "relation_vocab_partial.json").unlink(missing_ok=True)
    (d / "relation_map_partial.jsonl").unlink(missing_ok=True)

    print(f"\n  consolidated: {len(rel_by_count)} -> {len(relations)} relation types")
    print("  top:", ", ".join(f"{r['type']}({r['count']})" for r in relations[:12]))
    print(f"  backup: kg_raw.jsonl   map: relation_map.json")
    print(f"  next: akg graph load")


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="LLM relation consolidation (remap edges, no re-extract).")
    ap.add_argument("--benchmark", required=True)
    ap.add_argument("--vocab-size", type=int, default=S.cfg()["consolidate"]["vocab_size"], help="Top phrases used to seed the vocab.")
    ap.add_argument("--target", type=int, default=S.cfg()["consolidate"]["target"], help="Approx max canonical relations.")
    ap.add_argument("--chunk", type=int, default=S.cfg()["consolidate"]["chunk"], help="Phrases per mapping call.")
    ap.add_argument("--workers", type=int, default=S.cfg()["consolidate"]["workers"], help="Concurrent mapping calls (rate-limit safe).")
    ap.add_argument("--reuse-map", action="store_true",
                    help="Reapply the existing relation_map.json deterministically — no LLM "
                         "calls. Use after re-running build_kg --mode openie from cache (e.g. "
                         "to pick up resolver changes), which regenerates kg.jsonl with raw "
                         "phrases again.")
    args = ap.parse_args(argv)
    if args.reuse_map:
        print(f"Consolidating relations for {args.benchmark} (reusing saved map, no LLM) ...")
    else:
        print(f"Consolidating relations for {args.benchmark} (model={_cons_llm().model}) ...")
    consolidate(args.benchmark, args.vocab_size, args.target, args.chunk, args.workers,
               reuse_map=args.reuse_map)


if __name__ == "__main__":
    main()
